# frozen_string_literal: true

require "minitest/autorun"
require "fileutils"
require "tmpdir"
require_relative "../lib/zui"

class QtCoverageTest < Minitest::Test
  ROOT = File.expand_path("..", __dir__)
  DOCUMENT = File.join(ROOT, "docs", "qt-coverage.md")
  # Faults the report already reports, each a component whose adapter names a Qt type or module
  # version the pinned Qt does not provide. Fixing one is a component change; this list exists so a
  # fourth cannot appear unnoticed.
  KNOWN_FAULTS = {
    "Components/Builtins/RectangularShadow.qml" =>
      "RectangularShadow arrived in Qt 6.9, so the adapter instantiates itself",
    "Components/Builtins/SortFilterProxyModel.qml" =>
      "SortFilterProxyModel and StringSorter come from a third-party QML library",
    "Components/Builtins/TreeView.qml" =>
      "the runtime-assembled model asks for Qt.labs.qmlmodels 6.10"
  }.freeze

  def document
    @document ||= File.read(DOCUMENT, encoding: "UTF-8")
  end

  # Reports built without a Qt SDK answer everything that comes from the registry and the catalog.
  def report(qt_root: "/nonexistent")
    Zui::QtCoverageReport.new(qt_root:)
  end

  def installed_qt_root
    [ENV["ZUI_QT_HOST"], File.join(ROOT, "tmp", "Qt", Zui::QtModules.qt_version, "macos")]
      .compact.find { |path| File.directory?(File.join(path, "qml")) }
  end

  def test_the_document_is_generated_and_names_the_pinned_qt_version
    assert_path_exists DOCUMENT
    assert_includes document, "Generated by `rake qt:coverage`"
    assert_includes document, "the Qt #{Zui::QtModules.qt_version} SDKs"
    assert_includes document, "Do\nnot edit by hand."
  end

  # The alias table is the mapping the mobile catalog holds and nothing else; it is the part of the
  # document that must not drift, because it is what makes the catalog searchable by Qt name.
  def test_the_alias_table_matches_the_mobile_catalog
    section = document[/## Qt name to Zui name\n(.*?)\n## /m, 1]
    documented = section.scan(/^\| `([^`]+)` \| `([^`]+)` \|$/).to_h { |qt, zui| [qt, zui.to_sym] }

    refute_empty documented
    assert_equal report.aliases, documented
    assert_equal "dropdown", documented.fetch("ComboBox").to_s
    assert_equal "toggle_switch", documented.fetch("Switch").to_s
    assert_equal "progress", documented.fetch("ProgressBar").to_s
    assert_equal "scroll", documented.fetch("ScrollView").to_s
    assert_equal "tooltip", documented.fetch("ToolTip").to_s
    assert_equal "file_picker", documented.fetch("FileDialog").to_s
  end

  def test_every_component_named_in_the_document_is_registered
    mapped = document.scan(/^\| `[A-Z][^`]*` \| `([a-z][a-z0-9_]*)` \|$/).flatten
    native = document[/## Zui components with no Qt counterpart\n(.*)\z/m, 1].to_s
                     .scan(/`([a-z][a-z0-9_]*)`/).flatten
    named = (mapped + native).uniq.map(&:to_sym)

    refute_empty mapped
    refute_empty native
    assert_empty named.reject { |name| Zui::COMPONENTS.key?(name) },
                 "run `rake qt:coverage` to regenerate docs/qt-coverage.md"
    assert_equal Zui::COMPONENTS.keys.size, (named & Zui::COMPONENTS.keys).size
  end

  # Every group of the mobile catalog has to be attributed to the Qt module it describes, or the
  # report cannot tell real coverage from a Qt type name that two modules happen to share.
  def test_every_catalog_group_is_attributed_to_a_qt_module
    unattributed = report.unattributed_groups

    assert_empty unattributed,
                 "add #{unattributed.join(', ')} to Zui::QtCoverageReport::CATALOG_MODULES"
  end

  def test_the_document_lists_the_known_unsupported_references
    section = document[/## Adapters the pinned Qt cannot satisfy\n(.*?)\n## /m, 1]
    sources = section.scan(/^\| `([^`]+)` \|/).flatten.uniq

    refute_empty sources
    assert_empty sources - KNOWN_FAULTS.keys
  end

  # The fault the rest of the suite cannot see: an adapter that assembles QML for
  # Qt.createQmlObject in a string, where a `^import` scan, qmllint and the contract tests all miss
  # the type and the version it asks for. Checked against a written-out adapter so the detector
  # stays covered once the adapters it currently reports are fixed.
  def test_the_detector_reads_runtime_constructed_qml
    root = installed_qt_root
    skip "no Qt #{Zui::QtModules.qt_version} SDK installed" unless root

    Dir.mktmpdir do |framework|
      builtins = File.join(framework, "Components", "Builtins")
      FileUtils.mkdir_p(builtins)
      File.write(File.join(builtins, "Probe.qml"), <<~QML)
        import QtQuick
        Item {
          required property var renderer
          function modelSource() {
            return "import Qt.labs.qmlmodels 6.10\nTreeModel {\n}"
          }
        }
      QML
      faults = Zui::QtCoverageReport.new(qt_root: root, framework_root: framework)
                                    .unsupported_references

      assert_equal ["Qt.labs.qmlmodels 6.10", "TreeModel"], faults.map(&:subject).sort
      assert_equal %i[module_version unknown_type], faults.map(&:kind).sort
      assert_equal ["Components/Builtins/Probe.qml"], faults.map(&:source).uniq
    end
  end

  # A type a Qt module declares in a QML file appears in its qmldir and in no .qmltypes, so a
  # report that read only the type descriptions would call every Qt5Compat effect missing.
  def test_types_declared_only_in_a_qmldir_are_known
    root = installed_qt_root
    skip "no Qt #{Zui::QtModules.qt_version} SDK installed" unless root

    declared = report(qt_root: root).send(:declared_types)

    assert_includes declared.fetch("Qt5Compat.GraphicalEffects"), "RectangularGlow"
    assert_includes declared.fetch("Qt5Compat.GraphicalEffects"), "GaussianBlur"
    assert_includes declared.fetch("QtQuick.Controls.Basic"), "ComboBox"
  end

  # The live check: with a Qt SDK present, no new adapter may reference a type or module version
  # the pinned Qt does not provide.
  def test_no_new_adapter_references_a_type_the_pinned_qt_lacks
    root = installed_qt_root
    skip "no Qt #{Zui::QtModules.qt_version} SDK installed" unless root

    faults = report(qt_root: root).unsupported_references
    unknown = faults.map(&:source).uniq - KNOWN_FAULTS.keys

    assert_empty unknown,
                 "#{unknown.join(', ')} reference a Qt type or version that Qt " \
                 "#{Zui::QtModules.qt_version} does not provide"
  end

  def test_the_report_attributes_coverage_through_the_catalog_group
    root = installed_qt_root
    skip "no Qt #{Zui::QtModules.qt_version} SDK installed" unless root

    modules = report(qt_root: root).modules.to_h { |entry| [entry.name, entry] }

    # Qt.labs.platform declares MessageDialog, FileDialog and FontDialog as well, but no adapter
    # imports it, so none of its types may be reported as covered.
    assert_empty modules.fetch("Qt.labs.platform").covered_types
    refute modules.fetch("Qt.labs.platform").imported?
    # QtQuick.Templates mirrors the whole Controls catalog and is likewise never imported.
    assert_empty modules.fetch("QtQuick.Templates").covered_types
    assert_includes modules.fetch("QtQuick.Controls").components, :dropdown
    assert_includes modules.fetch("QtSensors").components, :accelerometer
  end
end
